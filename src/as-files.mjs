const fail = message => { throw new Error(`as: ${message}`); };

export function assertPrivateDir(dir) {
  let stat;
  try { stat = fs.statSync(dir); } catch { fail(`directory ${dir} is missing`); }
  if (!stat.isDirectory()) fail(`${dir} is not a directory`);
  if ((stat.mode & 0o077) !== 0) fail(`directory ${dir} must be mode 0700`);
  if (typeof process.getuid === 'function' && stat.uid !== process.getuid()) fail(`directory ${dir} must belong to the bridge user`);
}

// Write to a new 0600 file, flush it, then rename it over the target. A crash leaves the old file or the new file, never half of one.
export function writeAtomic(file, text) {
  const temp = `${file}.${process.pid}.${randomBytes(6).toString('hex')}.tmp`;
  const fd = fs.openSync(temp, 'wx', 0o600);
  try {
    fs.writeSync(fd, text);
    fs.fsyncSync(fd);
  } catch (error) {
    fs.closeSync(fd);
    fs.rmSync(temp, { force: true });
    throw error;
  }
  fs.closeSync(fd);
  fs.renameSync(temp, file);
  const dirFd = fs.openSync(path.dirname(file), 'r');
  try { fs.fsyncSync(dirFd); } finally { fs.closeSync(dirFd); }
}

function readPrivateJson(file, what) {
  let stat;
  try { stat = fs.statSync(file); } catch { fail(`${what} is missing (${file}); run dalan as-init`); }
  if (!stat.isFile() || (stat.mode & 0o777) !== 0o600) fail(`${what} must be a regular file with mode 0600`);
  try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch { fail(`${what} is not valid JSON`); }
}

// ---- callback patterns -------------------------------------------------------------------------------------------
// A pattern is `https://host[:port]/path`. Scheme, host and port must match exactly. In the path a `*` stands for one
// segment of letters, digits, `_` and `-`. A redirect URI never carries a query or a fragment.
export function parseCallbackPattern(pattern, { loopback = false, allowLoopback = true } = {}) {
  if (typeof pattern !== 'string' || pattern.length > 512 || /[\s\u0000-\u001f\u007f]/u.test(pattern)) fail('callback pattern must be a short string without spaces');
  if (allowLoopback && typeof pattern === 'string' && pattern.startsWith('http://')) {
    try { return parseNativeLoopback(pattern, true); }
    catch (error) { if (/omit the port/.test(error.message)) throw error; fail('HTTP is only allowed for canonical native loopback callbacks'); }
  }
  if (!pattern.startsWith('https://')) fail(pattern.startsWith('http://') ? 'HTTP is only allowed for canonical native loopback callbacks' : 'callback pattern must use https');
  if (/[?#@\\]/.test(pattern)) fail('callback pattern must not have credentials, a query or a fragment');
  const slash = pattern.indexOf('/', 'https://'.length);
  if (slash < 0) fail('callback pattern needs a path');
  const authority = pattern.slice('https://'.length, slash), rawPath = pattern.slice(slash);
  if (!authority || authority.includes('*')) fail('callback pattern host and port must be exact');
  let origin;
  try { origin = new URL(`https://${authority}/`).origin; } catch { fail(`callback pattern host ${JSON.stringify(authority)} is invalid`); }
  if (!/^\/[A-Za-z0-9._~\-\/*]*$/.test(rawPath)) fail('callback pattern path has unsupported characters');
  const segments = rawPath.split('/').slice(1);
  if (segments.some(s => s === '' && rawPath !== '/' ) || segments.some(s => s === '.' || s === '..' || (s.includes('*') && s !== '*'))) fail('callback pattern path is not canonical; a * must be a whole segment');
  const regex = new RegExp('^/' + segments.map(s => s === '*' ? '[A-Za-z0-9_-]+' : s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('/') + '$');
  return { pattern, origin, regex };
}
export function parseNativeLoopback(uri, pattern = false) {
  if (typeof uri !== 'string' || uri.length > 512 || /[?#@\\\s\u0000-\u001f\u007f%]/u.test(uri)) fail('native callback must be canonical and contain no query, fragment, userinfo or escapes');
  const match = /^http:\/\/(127\.0\.0\.1|localhost|\[::1\])(?::([0-9]+))?(\/[^?#@\\\s\u0000-\u001f\u007f%]*)$/.exec(uri);
  if (!match) fail('native callback host or URI syntax is not allowed');
  const [, hostname, port, pathname] = match;
  if (pattern && port) fail('omit the port in a native callback pattern');
  if (port && (String(Number(port)) !== port || Number(port) < 1 || Number(port) > 65535)) fail('native callback port must be from 1 to 65535');
  const segments = pathname.split('/').slice(1);
  if (pathname !== '/' && segments.some(s => !s || s === '.' || s === '..' || !/^[A-Za-z0-9._~-]+$/.test(s))) fail('native callback path must contain exact canonical segments');
  let url;
  try { url = new URL(uri); } catch { fail('invalid native callback'); }
  if (url.href !== uri) fail('native callback must use canonical spelling');
  return { pattern: pattern ? uri : undefined, loopback: true, hostname, pathname, port: port || '' };
}
// Older as.json files could contain non-canonical native paths. Keep those exact owner-approved paths loadable;
// new registrations still go through parseNativeLoopback above.
function parseStoredNativeLoopback(uri) {
  if (typeof uri !== 'string' || uri.length > 512 || /[?#@\\\s\u0000-\u001f\u007f]/u.test(uri)) fail('stored native callback is invalid');
  const match = /^http:\/\/(127\.0\.0\.1|localhost|\[::1\])(?::([0-9]+))?(\/[^?#@\\\s\u0000-\u001f\u007f]*)$/.exec(uri);
  if (!match) return parseNativeLoopback(uri, true);
  if (match[2] && (String(Number(match[2])) !== match[2] || Number(match[2]) < 1 || Number(match[2]) > 65535)) fail('stored native callback port is invalid');
  return { pattern: uri, loopback: true, hostname: match[1], pathname: match[3], port: match[2] || '' };
}
export function isLoopbackCallback(url) {
  try { return parseStoredNativeLoopback(url.href).hostname === url.hostname; } catch { return false; }
}
export function matchesCallback(patterns, uri) {
  if (typeof uri !== 'string') return false;
  let url;
  try { url = new URL(uri); } catch { return false; }
  let native;
  if (uri.startsWith('http://')) { try { native = parseStoredNativeLoopback(uri); } catch { return false; } }
  // The registered string must already be in canonical form: no hidden normalisation, no userinfo, no query, no fragment.
  if (url.href !== uri || !['https:', 'http:'].includes(url.protocol) || url.username || url.password || url.search || url.hash) return false;
  return patterns.some(p => p.loopback
    ? !!native && p.hostname === native.hostname && p.pathname === native.pathname
    : url.protocol === 'https:' && p.origin === url.origin && p.regex.test(url.pathname));
}

// ---- as.json -----------------------------------------------------------------------------------------------------
export function parseAsConfig(value, { allowHttp = false, loopback = false, allowLoopback = true, stored = false } = {}) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) fail('as.json must be an object');
  for (const key of Object.keys(value)) if (!['version', 'public_url', 'callbacks', 'limits'].includes(key)) fail(`unknown key ${key} in as.json`);
  if (value.version !== 1) fail('as.json version must be 1');
  let url;
  try { url = new URL(value.public_url); } catch { fail('public_url is not a URL'); }
  const origin = url.origin;
  if (value.public_url !== origin && value.public_url !== `${origin}/`) fail('public_url must be an origin: scheme, host and optional port');
  if (url.protocol !== 'https:' && !((allowHttp || loopback && url.hostname === '127.0.0.1') && url.protocol === 'http:')) fail('public_url must be https (an http test URL needs the explicit test flag)');
  if (!Array.isArray(value.callbacks) || value.callbacks.length > 32) fail('callbacks must be an array of at most 32 patterns');
  const limits = { registrations: 5, interactions: 5, ...value.limits };
  if (value.limits !== undefined && (!value.limits || typeof value.limits !== 'object' || Array.isArray(value.limits))) fail('limits must be an object');
  for (const [key, n] of Object.entries(limits)) {
    if (!['registrations', 'interactions'].includes(key) || !Number.isInteger(n) || n < 1 || n > 100) fail('limits must contain registrations/interactions integers from 1 to 100');
  }
  const patterns = value.callbacks.map(pattern => stored && typeof pattern === 'string' && pattern.startsWith('http://') ? parseStoredNativeLoopback(pattern) : parseCallbackPattern(pattern, { loopback, allowLoopback }));
  return { public_url: origin, callbacks: patterns.map(p => p.pattern), patterns, limits };
}
export function loadAsConfig(dir, opts) {
  assertPrivateDir(dir);
  return parseAsConfig(readPrivateJson(asFiles(dir).config, 'as.json'), { ...opts, stored: true });
}
export function saveAsCallbacks(dir, callbacks) {
  const file = asFiles(dir).config;
  const current = readPrivateJson(file, 'as.json');
  writeAtomic(file, JSON.stringify({ ...current, callbacks }, null, 2) + '\n');
}

// ---- keys --------------------------------------------------------------------------------------------------------
// as-jwks.json:        { signing_kid, retired: { <kid>: <retired_at ms | null> }, keys: [private ES256 JWKs] }
// as-cookie-keys.json: { keys: [ { key }, { key, retired_at: <ms | null> }, ... ] }   (first entry signs)
// Retirement starts at rotation: exclusive ownership proves the previous signer has stopped. Keep old keys for the full
// ID-token, session and interaction lifetimes, plus skew. Legacy null stamps remain retained.
// How long one pairing attempt stays open for the owner to approve.
export const PAIRING_MINUTES = 10;
export const LIFETIMES = Object.freeze({ idToken: 600, session: 3600, interaction: 600, skew: 75 });
export const JWKS_RETAIN_MS = (LIFETIMES.idToken + LIFETIMES.skew) * 1000;
export const COOKIE_RETAIN_MS = (Math.max(LIFETIMES.session, LIFETIMES.interaction) + LIFETIMES.skew) * 1000;
const B64 = /^[A-Za-z0-9_-]{43}$/;

// A key is valid only if it works: import the private part, derive its public part, compare with the stated x and y,
// then sign and verify a message. A well-formed JWK with a swapped scalar fails here.
function assertWorkingEcKey(key) {
  try {
    const priv = createPrivateKey({ key, format: 'jwk' });
    const derived = createPublicKey(priv).export({ format: 'jwk' });
    if (derived.x !== key.x || derived.y !== key.y) throw new Error('private part does not match public part');
    const pub = createPublicKey({ key: { kty: 'EC', crv: 'P-256', x: key.x, y: key.y }, format: 'jwk' });
    const message = randomBytes(32);
    if (!cryptoVerify('sha256', message, pub, cryptoSign('sha256', message, priv))) throw new Error('sign/verify round trip failed');
  } catch (error) { fail(`as-jwks.json key ${JSON.stringify(String(key.kid))} is not a working ES256 key (${error.message})`); }
}
const MAX_KEYS = 8;
// The one validation for as-jwks.json contents. loadKeys and rotateKeys both use it, so a rotation can never write what a load rejects.
function validateJwks(jwks) {
  if (!jwks || typeof jwks !== 'object' || !Array.isArray(jwks.keys) || !jwks.keys.length || jwks.keys.length > MAX_KEYS) fail(`as-jwks.json must hold 1 to ${MAX_KEYS} keys`);
  const kids = new Set();
  for (const key of jwks.keys) {
    const ok = key && key.kty === 'EC' && key.crv === 'P-256' && key.alg === 'ES256' && key.use === 'sig' && typeof key.kid === 'string' && key.kid
      && ['x', 'y', 'd'].every(part => typeof key[part] === 'string' && B64.test(key[part]));
    if (!ok || kids.has(key.kid)) fail('as-jwks.json holds a damaged or duplicate key');
    kids.add(key.kid);
  }
  if (!kids.has(jwks.signing_kid)) fail('as-jwks.json signing_kid names no key');
  if (!jwks.retired || typeof jwks.retired !== 'object' || Array.isArray(jwks.retired)) fail('as-jwks.json retired must be an object');
  for (const kid of kids) if (kid !== jwks.signing_kid && !Object.hasOwn(jwks.retired, kid)) fail('as-jwks.json holds a key that is neither signing nor retired');
  for (const [kid, at] of Object.entries(jwks.retired)) if (!kids.has(kid) || kid === jwks.signing_kid || !(at === null || Number.isSafeInteger(at))) fail('as-jwks.json retired list is damaged');
  return jwks;
}
function validateCookies(file) {
  const keys = file?.keys;
  if (!Array.isArray(keys) || !keys.length || keys.length > MAX_KEYS) fail('as-cookie-keys.json is damaged');
  keys.forEach((entry, i) => {
    const ok = entry && typeof entry.key === 'string' && /^[A-Za-z0-9_-]{43,}$/.test(entry.key) && (i === 0 ? entry.retired_at === undefined : (entry.retired_at === null || Number.isSafeInteger(entry.retired_at)));
    if (!ok) fail('as-cookie-keys.json is damaged');
  });
  return file;
}
const readJwks = dir => validateJwks(readPrivateJson(asFiles(dir).jwks, 'as-jwks.json'));
const readCookies = dir => validateCookies(readPrivateJson(asFiles(dir).cookies, 'as-cookie-keys.json'));
export function loadKeys(dir) {
  assertPrivateDir(dir);
  const jwks = readJwks(dir), cookies = readCookies(dir);
  for (const key of jwks.keys) assertWorkingEcKey(key);
  // The provider signs with the first key. The signing kid is chosen explicitly and put first.
  const ordered = [jwks.keys.find(k => k.kid === jwks.signing_kid), ...jwks.keys.filter(k => k.kid !== jwks.signing_kid)];
  return { jwks: { keys: ordered }, signingKid: jwks.signing_kid, cookieKeys: cookies.keys.map(e => e.key) };
}
const newEcKey = () => ({ ...generateKeyPairSync('ec', { namedCurve: 'P-256' }).privateKey.export({ format: 'jwk' }), use: 'sig', alg: 'ES256', kid: randomUUID() });

// ---- exclusive ownership of the AS state -------------------------------------------------------------------------
// Hold this exclusive transaction for the owner's lifetime. The kernel releases it on exit, SIGTERM or SIGKILL.
// Never unlink this database: every starter and rotation must contend on the same inode.
export function acquireAsOwner(dir) {
  assertPrivateDir(dir);
  // Linux magic values from linux/magic.h. These filesystems cannot provide the local ownership guarantee.
  if (process.platform === 'linux') {
    const type = Number(fs.statfsSync(dir).type) >>> 0;
    if ([0x6969, 0x517b, 0xff534d42, 0xfe534d42, 0x65735546].includes(type)) fail('AS state must use a local filesystem; NFS, SMB/CIFS and FUSE are unsupported. For a trial, use a short directory on a local disk: dalan try --home /short/local/path (not your real home or an existing bridge home)');
  }
  // Keep this path private: a same-process raw open/close can release SQLite's POSIX lock.
  const file = path.join(dir, 'as-owner.sqlite');
  // Do not open/close a raw descriptor for an existing SQLite file: POSIX close would release this process's locks.
  try { fs.closeSync(fs.openSync(file, 'wx', 0o600)); }
  catch (error) { if (error.code !== 'EEXIST') throw error; }
  const stat = fs.lstatSync(file);
  if (!stat.isFile() || (stat.mode & 0o777) !== 0o600) fail('as-owner.sqlite must be a regular file with mode 0600');
  const db = new DatabaseSync(file);
  try { db.exec('PRAGMA busy_timeout=500; BEGIN EXCLUSIVE'); }
  catch (error) {
    db.close();
    if (error.code === 'ERR_SQLITE_ERROR' && error.errcode === 5) fail('AS ownership unavailable after waiting up to 500 ms (database is locked): another bridge, key rotation or init holds it. To rotate keys: stop the bridge, rotate, start');
    throw error;
  }
  let released = false;
  const release = () => {
    if (released) return;
    released = true;
    process.removeListener('exit', release);
    db.close();
  };
  process.once('exit', release);
  return {
    release,
    pruneKeys(now = Date.now()) {
      if (released) fail('AS ownership has been released');
      return pruneKeys(dir, now);
    },
  };
}

// Drop retired entries whose stamp is past the retention window. Pure: returns new contents.
const prunedJwks = (jwks, now) => {
  const retired = Object.fromEntries(Object.entries(jwks.retired).filter(([, at]) => at === null || at + JWKS_RETAIN_MS > now));
  return { ...jwks, retired, keys: jwks.keys.filter(k => k.kid === jwks.signing_kid || Object.hasOwn(retired, k.kid)) };
};
const prunedCookies = (file, now) => ({ keys: file.keys.filter((e, i) => i === 0 || e.retired_at === null || e.retired_at + COOKIE_RETAIN_MS > now) });
const sameKeys = (a, b) => a.keys.length === b.keys.length;
const legacyKeys = (entries, label) => {
  const names = entries.filter(([, at]) => at === null).map(([name]) => name);
  return names.length ? `; legacy unstamped ${label}: ${names.join(', ')} (retained indefinitely; see docs/operations.md#legacy-unstamped-keys)` : '';
};
const freeAt = (stamps, retain) => { const stamped = stamps.filter(Number.isSafeInteger); return stamped.length ? new Date(Math.min(...stamped) + retain).toISOString() : null; };

// Rotation is offline: the lifetime lock excludes every server and other rotation. The previous signer has stopped.
// The prospective contents (expired keys pruned first) go through the same validation as a load; a rotation that would leave
// an unloadable state is refused and nothing on disk changes.
export function rotateKeys(dir, { jwks = true, cookies = true } = {}, now) {
  assertPrivateDir(dir);
  const files = asFiles(dir);
  const owner = acquireAsOwner(dir);
  try {
    now ??= Date.now(); // Sample only after ownership; this command may have been paused before it acquired the lock.
    loadKeys(dir); // Validate both existing files before planning any write.
    const out = {}, writes = [];
    if (jwks) {
      const current = prunedJwks(readJwks(dir), now);
      const key = newEcKey();
      assertWorkingEcKey(key);
      const next = { signing_kid: key.kid, retired: { ...current.retired, [current.signing_kid]: now }, keys: [key, ...current.keys] };
      if (next.keys.length > MAX_KEYS) fail(`too many retained signing keys; wait until ${freeAt(Object.values(current.retired), JWKS_RETAIN_MS) ?? 'no timed expiry'}${legacyKeys(Object.entries(current.retired), 'signing kids')}`);
      validateJwks(next);
      writes.push([files.jwks, next]); out.signing_kid = key.kid;
    }
    if (cookies) {
      const current = prunedCookies(readCookies(dir), now);
      const [active, ...rest] = current.keys;
      const next = { keys: [{ key: randomBytes(32).toString('base64url') }, { key: active.key, retired_at: now }, ...rest] };
      if (next.keys.length > MAX_KEYS) fail(`too many retained cookie keys; wait until ${freeAt(rest.map(e => e.retired_at), COOKIE_RETAIN_MS) ?? 'no timed expiry'}${legacyKeys(current.keys.map((e, i) => [String(i), e.retired_at]), 'cookie positions')}`);
      validateCookies(next);
      writes.push([files.cookies, next]); out.cookie_key_rotated = true;
    }
    for (const [file, contents] of writes) writeAtomic(file, JSON.stringify(contents, null, 2) + '\n');
    loadKeys(dir);
    return out;
  } finally { owner.release(); }
}
// Only the lifetime lock owner can prune, before loading the provider's signing keys.
function pruneKeys(dir, now) {
  const files = asFiles(dir);
  const jwks = readJwks(dir), cookies = readCookies(dir), changed = { pruned: 0 };
  const j = prunedJwks(jwks, now), c = prunedCookies(cookies, now);
  if (!sameKeys(j, jwks)) { writeAtomic(files.jwks, JSON.stringify(validateJwks(j), null, 2) + '\n'); changed.pruned += jwks.keys.length - j.keys.length; }
  if (!sameKeys(c, cookies)) { writeAtomic(files.cookies, JSON.stringify(validateCookies(c), null, 2) + '\n'); changed.pruned += cookies.keys.length - c.keys.length; }
  return changed;
}

// `init`: create the directory, as.json and the keys. It never overwrites a key and never changes an existing public_url.
export function initAsFiles(dir, { publicUrl, allowHttp = false, loopback = false }) {
  fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  fs.chmodSync(dir, 0o700);
  assertPrivateDir(dir);
  const files = asFiles(dir);
  const wanted = parseAsConfig({ version: 1, public_url: publicUrl, callbacks: [...DEFAULT_CALLBACKS] }, { allowHttp, loopback });
  // Reinitializing complete state is read-only. Any creation must own the same lock as a server or rotation.
  const complete = [files.config, files.jwks, files.cookies].every(file => fs.existsSync(file));
  const owner = complete ? null : acquireAsOwner(dir);
  try {
    const created = [];
    if (fs.existsSync(files.config)) {
      const existing = loadAsConfig(dir, { allowHttp, loopback });
      if (existing.public_url !== wanted.public_url) fail(`as.json already names ${existing.public_url}; changing the public URL changes the issuer and ends every connection. Remove ${files.config} to start over`);
    } else {
      writeAtomic(files.config, JSON.stringify({ version: 1, public_url: wanted.public_url, callbacks: wanted.callbacks }, null, 2) + '\n');
      created.push('as.json');
    }
    const hasJwks = fs.existsSync(files.jwks), hasCookies = fs.existsSync(files.cookies);
    if (hasJwks !== hasCookies) fail('one key file exists and the other is missing; refusing to guess. Fix or remove both');
    if (!hasJwks) {
      const jwk = newEcKey();
      writeAtomic(files.jwks, JSON.stringify({ signing_kid: jwk.kid, retired: {}, keys: [jwk] }, null, 2) + '\n');
      writeAtomic(files.cookies, JSON.stringify({ keys: [{ key: randomBytes(32).toString('base64url') }] }, null, 2) + '\n');
      created.push('as-jwks.json', 'as-cookie-keys.json');
    }
    loadKeys(dir); // read back what was written
    return { dir, public_url: wanted.public_url, created };
  } finally { owner?.release(); }
}

export const normalizeCode = value => String(value ?? '').toUpperCase().replace(/[^A-Z0-9]/g, '');
