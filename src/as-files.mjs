  'https://claude.ai/api/mcp/auth_callback',
  // https://developers.openai.com/apps-sdk/build/auth, "Redirect URL": the stable URI and the callback-ID-specific URI.
  'https://chatgpt.com/connector_platform_oauth_redirect',
