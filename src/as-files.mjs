import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { generateKeyPairSync, randomBytes, randomUUID, createPrivateKey, createPublicKey, sign as cryptoSign, verify as cryptoVerify } from 'node:crypto';

// Text that comes from a vendor: no control, format or separator characters (terminal escapes, bidi overrides), bounded length.
// It lives here, not in as.mjs, so the dalan CLI can use it without loading oidc-provider.
export const untrusted = (value, max = 80) => String(value ?? '').replace(/[\p{C}\p{Z}]+/gu, ' ').trim().slice(0, max);

// Files of the built-in authorization server (AS). All of them live in one 0700 directory and are 0600 files.
// Keys are generated by `init` only. A server start never creates them: a missing or damaged key file stops the start.
export const asFiles = dir => ({
  config: path.join(dir, 'as.json'),
  jwks: path.join(dir, 'as-jwks.json'),
  cookies: path.join(dir, 'as-cookie-keys.json'),
  db: path.join(dir, 'as.sqlite'),
});

// Vendor callbacks that the vendors publish. Each entry cites its source. Grok has no published OAuth callback: none is shipped.
