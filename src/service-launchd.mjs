// The macOS service backend: a LaunchAgent for the bridge and a second one that runs `dalan service update` every day.
// Everything here is plist text (pure) plus a thin launchctl seam, so Linux tests can fake launchctl. The shape follows the agent
// that scripts/worker-bridge-setup.mjs already runs on macOS 26 (domain user/UID, Aqua and Background sessions, an explicit kickstart).
//
// Rules this backend keeps:
// - The agent runs node by absolute path. `nodePath()` in service.mjs picks the stable Homebrew or mise symlink when node is one of those, so a
//   node upgrade keeps working; any other node is recorded as is, and a move of that binary needs `dalan service install` again.
// - It runs the package through the home's `current` symlink, so the updater switches versions by repointing that link and restarting.
// - launchd has no pre-start step, so the agent runs `dalan service recover` first in a shell, and starts the server only if that succeeds.
// - KeepAlive restarts after a crash or an error exit, never after a clean exit. Logs live under the service home.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';

export const MARKER = 'Generated by dalan service install';
const SESSION_TYPES = ['Aqua', 'Background'];
const SAFE_PATH = /^[A-Za-z0-9_@+=:,./-]+$/;
const fail = message => { throw new Error(message); };

export const launchdLabels = unit => ({ service: `org.dalan.${unit}`, update: `org.dalan.${unit}-update` });
export const launchAgentsDir = (env = process.env) => path.join(env.HOME || os.homedir(), 'Library', 'LaunchAgents');
const agentPath = (node) => [...new Set([path.dirname(node), '/opt/homebrew/bin', '/usr/local/bin', '/usr/bin', '/bin'])].join(':');
const xml = text => String(text).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function assertSafe(values) {
  for (const [label, value] of Object.entries(values)) if (!path.isAbsolute(value) || !SAFE_PATH.test(value)) fail(`${label} is not a safe absolute path for a LaunchAgent: ${JSON.stringify(value)}`);
}

const dict = entries => ['<dict>', ...entries.flatMap(([key, value]) => [`  <key>${xml(key)}</key>`, ...value.split('\n').map(line => `  ${line}`)]), '</dict>'].join('\n');
const str = value => `<string>${xml(value)}</string>`;
const arr = items => ['<array>', ...items.map(item => `  ${str(item)}`), '</array>'].join('\n');
const plist = (label, body) => ['<?xml version="1.0" encoding="UTF-8"?>',
  '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
  `<!-- ${MARKER}. Remove with: dalan service uninstall -->`, '<plist version="1.0">', body, '</plist>', ''].join('\n');

export function servicePlist({ unit, node, home, port, enableWorkspace = false, enableT3 = false }) {
  const current = path.join(home, 'current');
  assertSafe({ home, node, current });
  const { service } = launchdLabels(unit);
  const env = { HOME: home, NODE_ENV: 'production', DALAN_AUTH_MODE: 'builtin', DALAN_BIND_HOST: '127.0.0.1', DALAN_GOZAR_SERVICE: '1', DALAN_CATALOG_PROFILE: 'stable',
    DALAN_ENABLE_WORKSPACE: enableWorkspace ? '1' : '0', DALAN_ENABLE_T3_TOOLS: enableT3 ? '1' : '0', DALAN_PORT: String(port), PATH: agentPath(node) };
  const start = `${node} ${current}/bin/dalan.mjs service recover --home ${home} --quiet && exec ${node} ${current}/src/server.mjs`;
  return plist(service, dict([
    ['Label', str(service)],
    ['ProgramArguments', arr(['/bin/sh', '-c', start])],
    ['WorkingDirectory', str(current)],
    ['EnvironmentVariables', dict(Object.entries(env).map(([key, value]) => [key, str(value)]))],
    ['RunAtLoad', '<true/>'],
    ['KeepAlive', dict([['SuccessfulExit', '<false/>']])],
    ['ThrottleInterval', '<integer>5</integer>'],
    ['LimitLoadToSessionType', arr(SESSION_TYPES)],
    ['UMask', '<integer>63</integer>'],
    ['StandardOutPath', str(path.join(home, 'logs', 'bridge.out.log'))],
    ['StandardErrorPath', str(path.join(home, 'logs', 'bridge.err.log'))],
  ]));
}

// The update agent runs once a day at a fixed minute between 03:00 and 03:59 that depends on the home, so many installs do not call the registry together.
export const updateSchedule = home => ({ Hour: 3, Minute: parseInt(createHash('sha256').update(home).digest('hex').slice(0, 4), 16) % 60 });

export function updatePlist({ unit, node, home }) {
  const current = path.join(home, 'current');
  assertSafe({ home, node, current });
  const { update } = launchdLabels(unit), when = updateSchedule(home);
  return plist(update, dict([
    ['Label', str(update)],
    ['ProgramArguments', arr([node, `${current}/bin/dalan.mjs`, 'service', 'update', '--home', home, '--json'])],
    ['EnvironmentVariables', dict([['PATH', str(agentPath(node))]])],
    ['StartCalendarInterval', dict([['Hour', `<integer>${when.Hour}</integer>`], ['Minute', `<integer>${when.Minute}</integer>`]])],
    ['ProcessType', str('Background')],
    ['Nice', '<integer>19</integer>'],
    ['LowPriorityIO', '<true/>'],
    ['LimitLoadToSessionType', arr(SESSION_TYPES)],
    ['UMask', '<integer>63</integer>'],
    ['StandardOutPath', str(path.join(home, 'logs', 'update.out.log'))],
    ['StandardErrorPath', str(path.join(home, 'logs', 'update.err.log'))],
  ]));
}

// ---- launchctl --------------------------------------------------------------------------------------------------------------------------
export function launchctl(args, { spawn = spawnSync, env = process.env } = {}) {
  const result = spawn('launchctl', args, { encoding: 'utf8', env, timeout: 30000, maxBuffer: 1024 * 1024 });
  return { status: result.error ? -1 : (result.status ?? -1), stdout: result.stdout ?? '', stderr: result.error ? String(result.error.message) : (result.stderr ?? '') };
}
const uidOf = seams => (seams.uid ?? process.getuid?.());
const domainOf = seams => `user/${uidOf(seams)}`;
// Only launchctl's explicit missing-service diagnostic establishes absence.
export function queryAgent(label, seams = {}) {
  const result = launchctl(['print', `${domainOf(seams)}/${label}`], seams);
  const diagnostic = String(result.stderr || result.stdout).trim();
  const absent = result.status > 0 && diagnostic.includes(`Could not find service "${label}" in domain`);
  return { ...result, state: result.status === 0 ? 'loaded' : absent ? 'absent' : 'unknown' };
}
export function isLoaded(label, seams = {}) {
  const result = queryAgent(label, seams);
  if (result.state === 'unknown') fail(`Cannot determine whether launchd service ${label} is loaded; leaving its plist unchanged. launchctl print failed (exit ${result.status}): ${String(result.stderr || result.stdout).trim().slice(0, 500)}`);
  return result.state === 'loaded';
}
const must = (result, what) => { if (result.status !== 0) fail(`${what} failed (exit ${result.status}): ${String(result.stderr || result.stdout).trim().slice(0, 500)}`); };

// Load the agent from its plist, then ask launchd to start it: on macOS 26 a bootstrapped agent can stay loaded and never spawn.
export function loadAgent({ label, plistFile }, seams = {}) {
  const domain = domainOf(seams);
  if (!isLoaded(label, seams)) must(launchctl(['bootstrap', domain, plistFile], seams), `launchctl bootstrap ${domain} ${plistFile}`);
  const kick = launchctl(['kickstart', `${domain}/${label}`], seams);
  return { kicked: kick.status === 0, detail: kick.status === 0 ? '' : String(kick.stderr).trim() };
}

export function unloadAgent({ label }, seams = {}) {
  if (!isLoaded(label, seams)) return false;
  must(launchctl(['bootout', `${domainOf(seams)}/${label}`], seams), `launchctl bootout ${label}`);
  return true;
}

// The updater's three actions for a launchd service. `daemon-reload` has no launchd meaning: the plist does not change on update.
export function controlLaunchd(receipt, action, seams = {}) {
  const { service } = launchdLabels(receipt.unit), plistFile = path.join(receipt.unit_dir, `${service}.plist`);
  if (action === 'daemon-reload') return;
  if (action === 'stop') { unloadAgent({ label: service }, seams); return; }
  if (action === 'restart') {
    if (isLoaded(service, seams)) must(launchctl(['kickstart', '-k', `${domainOf(seams)}/${service}`], seams), `launchctl kickstart -k ${service}`);
    else {
      const { kicked, detail } = loadAgent({ label: service, plistFile }, seams);
      if (!kicked) fail(`launchctl kickstart ${service} failed: ${detail}`);
    }
    return;
  }
  fail('unsupported service action');
}

// ---- plist files ------------------------------------------------------------------------------------------------------------------------
// Read-only ownership/collision check. Return whether the generated plist needs writing.
export function preflightAgentFile(file, text) {
  let existing = null;
  try { const info = fs.lstatSync(file); if (!info.isFile() || info.isSymbolicLink()) fail(`${file} is not a regular file; refusing to replace it`); existing = fs.readFileSync(file, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (existing === text) return false;
  if (existing !== null && !existing.includes(MARKER)) fail(`${file} already exists and was not generated by dalan; refusing to overwrite it`);
  return true;
}

// Recheck at write time too, so a collision introduced after preflight is still refused.
export function writeAgentFile(file, text) {
  if (!preflightAgentFile(file, text)) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o755 });
  const temp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(temp, text, { mode: 0o644 });
  fs.renameSync(temp, file);
  return true;
}

export function lintPlist(file, { spawn = spawnSync } = {}) {
  const result = spawn('plutil', ['-lint', file], { encoding: 'utf8' });
  if (result.error) return null; // plutil is not installed (not macOS): not checked
  return result.status === 0;
}

// Turn the daily update agent on or off. Off removes the agent from launchd and deletes its plist.
export function setUpdateAgent({ receipt, home, node, enabled }, seams = {}) {
  const { update } = launchdLabels(receipt.unit), file = path.join(receipt.unit_dir, `${update}.plist`);
  if (enabled) {
    fs.mkdirSync(path.join(home, 'logs'), { recursive: true, mode: 0o700 });
    const changed = writeAgentFile(file, updatePlist({ unit: receipt.unit, node: receipt.node ?? node, home }));
    if (changed) unloadAgent({ label: update }, seams);
    if (!isLoaded(update, seams)) must(launchctl(['bootstrap', domainOf(seams), file], seams), `launchctl bootstrap ${file}`);
  } else {
    unloadAgent({ label: update }, seams);
    fs.rmSync(file, { force: true });
  }
  return { timer: update };
}

export function removeAgents({ unit, unit_dir: dir }, seams = {}) {
  const { service, update } = launchdLabels(unit), removed = [];
  // An unknown job must not allow even the other job's plist to be removed.
  for (const label of [update, service]) isLoaded(label, seams);
  for (const label of [update, service]) {
    if (unloadAgent({ label }, seams)) removed.push(`unloaded ${label}`);
    const file = path.join(dir, `${label}.plist`);
    if (fs.existsSync(file)) { if (!fs.readFileSync(file, 'utf8').includes(MARKER)) fail(`${file} was not generated by dalan; leaving it`); fs.rmSync(file); removed.push(`removed ${file}`); }
  }
  return removed;
}
