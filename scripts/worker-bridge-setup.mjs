// The real location of a path: the real path of its deepest existing ancestor, followed by the rest of the path.
function canonicalPath(target) {
  let head = path.resolve(target), tail = '';
  for (;;) {
    try { return path.join(fs.realpathSync(head), tail); } catch { /* not there (yet), or unreadable: try the parent */ }
    const parent = path.dirname(head);
    if (parent === head) return path.resolve(target);
    tail = path.join(path.basename(head), tail); head = parent;
  }
}

// Every path a unit or plist could name without quoting. A path that setup writes uses only SAFE_PATH characters, and = : ,
// are both path characters and separators (HOME=/a, PATH=/a:/b), so every way to cut a run of those characters at them is
// a candidate: it starts at any /, since a unit may put a prefix such as - + or @ before a path (WorkingDirectory=-/a), and
// ends at the end of the run or before = : or ,. A start inside a path only adds a shorter candidate, which can refuse a
// purge but never hides a match. Returns null past a fixed number of candidates, so a crafted file cannot make the check slow.
const UNIT_PATH_CANDIDATES_MAX = 20000;
function unitPathCandidates(text) {
  const out = [];
  for (const [run] of text.matchAll(/[A-Za-z0-9_@+=:,./-]+/g)) {
    const starts = [], ends = [];
    for (let i = 0; i < run.length; i += 1) {
      if (run[i] === '/') starts.push(i);
      if ('=:,'.includes(run[i])) ends.push(i);
    }
    ends.push(run.length);
    let first = 0; // starts and ends both ascend, so the ends after each start begin at a moving index
    for (const s of starts) {
      while (ends[first] <= s) first += 1;
      for (let k = first; k < ends.length; k += 1) {
        if (out.length >= UNIT_PATH_CANDIDATES_MAX) return null;
        out.push(run.slice(s, ends[k]));
      }
    }
  }
  return out;
}

// Files in the user's unit directory (other than the ones --remove is about to delete) that name this home. Such a file is
// a service that still uses the home, whatever its name or the release that wrote it. A symlink is followed: a unit linked
// into the directory is as live as one written there. Returns { named, unreadable }: a file that cannot be read is not
// evidence that it is unrelated, so the caller refuses on it. A link to nothing, or to something that is not a file (such as
// /dev/null, which masks a unit), cannot name a home and is skipped.
function unitsNamingHome(unitDir, home, skip) {
  const escaped = home.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const literal = new RegExp(`(?<![\\w./-])${escaped}(?![\\w.-])`);
  // A unit can name the home through another spelling of the same directory, such as a symlinked parent. Every absolute
  // path in the unit is compared by its real location as well.
  const real = canonicalPath(home);
  const namesHome = text => {
    if (literal.test(text)) return true;
    const candidates = unitPathCandidates(text);
    if (candidates === null) return null;
    return candidates.some(candidate => {
      const resolved = canonicalPath(candidate);
      return resolved === real || resolved.startsWith(real + '/');
    });
  };
  const named = [], unreadable = [];
  let entries;
  try { entries = fs.readdirSync(unitDir, { withFileTypes: true }); }
  catch (error) { return { named, unreadable: error.code === 'ENOENT' ? [] : [unitDir] }; }
  for (const entry of entries) {
    const file = path.join(unitDir, entry.name);
    if (skip.includes(file) || !(entry.isFile() || entry.isSymbolicLink())) continue;
    try {
      const stat = fs.statSync(file); // follows a link
      if (!stat.isFile()) continue;
      if (stat.size >= 1048576) { unreadable.push(file); continue; }
      const names = namesHome(fs.readFileSync(file, 'utf8'));
      if (names === null) unreadable.push(file); // too many possible paths to check: not evidence that it is unrelated
      else if (names) named.push(file);
    } catch (error) {
      if (entry.isSymbolicLink() && error.code === 'ENOENT') continue; // a dangling link
      unreadable.push(file);
    }
  }
  return { named, unreadable };
}

// Processes (other than this one) that hold a bridge database of this home open: { holders: [{ pid, command }], unknown }.
// `unknown` is null when the probe ran to the end, or a reason when it could not tell. An empty `holders` with a reason
// is NOT "nobody holds it": the caller must not act on it.
export function bridgeDatabaseHolders(home, { spawn = spawnSync, platform = process.platform, procRoot = '/proc' } = {}) {
  const isDb = file => file.startsWith(`${home}${path.sep}`) && /(^|\/)bridge\.db(-wal|-shm)?$/.test(file);
  const holders = new Map();
  let unknown = null;
  if (platform === 'linux') {
    let pids = [];
    try { pids = fs.readdirSync(procRoot).filter(n => /^\d+$/.test(n) && Number(n) !== process.pid); }
    catch (error) { return { holders: [], unknown: `${procRoot} could not be read (${error.code ?? error.message})` }; }
    // A process that exited while we looked is gone (ENOENT/ESRCH). One that refuses us (EACCES/EPERM: another user's, or a
    // same-user process that dropped its dumpable flag, such as ssh-agent) is not a bridge: the bridge is a plain node
    // process. Any other failure to read is a gap in the answer.
    const skippable = error => ['ENOENT', 'ESRCH', 'EACCES', 'EPERM'].includes(error.code);
    for (const pid of pids) {
      let fds;
      try { fds = fs.readdirSync(`${procRoot}/${pid}/fd`); }
      catch (error) { if (!skippable(error)) unknown ??= `the open files of process ${pid} could not be read (${error.code ?? error.message})`; continue; }
      for (const fd of fds) {
        let target;
        try { target = fs.readlinkSync(`${procRoot}/${pid}/fd/${fd}`); }
        catch (error) { if (!skippable(error)) unknown ??= `the open files of process ${pid} could not be read (${error.code ?? error.message})`; continue; }
        if (isDb(target)) { let command = ''; try { command = fs.readFileSync(`${procRoot}/${pid}/cmdline`, 'utf8').replace(/\0/g, ' ').trim(); } catch {} holders.set(pid, command); break; }
      }
    }
  } else {
    const r = spawn('lsof', ['-nP', '-F', 'pcn', '+D', home], { encoding: 'utf8', timeout: 10000, maxBuffer: 1 << 20 });
    let pid = null, command = '';
    for (const line of String(r.stdout ?? '').split('\n')) {
      if (line.startsWith('p')) { pid = line.slice(1); command = ''; }
      else if (line.startsWith('c')) command = line.slice(1);
      else if (line.startsWith('n') && pid && Number(pid) !== process.pid && isDb(line.slice(1))) holders.set(pid, command);
    }
    // lsof exits 1 with no output when nothing matched; any other failure leaves the answer incomplete.
    const cleanNone = r.status === 1 && !String(r.stdout ?? '').trim() && !String(r.stderr ?? '').trim();
    if (r.error) unknown = `lsof could not be run (${r.error.code ?? r.error.message})`;
    else if (r.signal) unknown = `lsof was stopped by ${r.signal}`;
    else if (r.status !== 0 && !cleanNone) unknown = `lsof failed (exit ${r.status}${String(r.stderr ?? '').trim() ? `: ${String(r.stderr).trim().slice(0, 120)}` : ''})`;
  }
  return { holders: [...holders].map(([pid, command]) => ({ pid, command })), unknown };
}

// Stop, then delete, only files that carry the marker. The refusals that need the unit directory and the bridge home
// happen before the first stop or delete; the check for a process that still holds the database follows the stop, because
// the service that was just stopped needs a moment to exit.
function removeUnit(o, { platform, env, log, spawn = spawnSync, holderProbe = home => bridgeDatabaseHolders(home, { spawn }) }) {
  const unitDir = unitDirFor(platform, env);
  if (!unitDir) fail('--remove is not supported on this platform (only Linux and macOS have units)');
  const linux = platform === 'linux';
  const name = `dot-bridge-${o.worker}`;
  const names = linux ? [`${name}.service`, `${name}-lan.socket`, `${name}-lan.service`] : [`${launchLabel(o.worker)}.plist`];
  const present = names.map(n => path.join(unitDir, n)).filter(f => fs.existsSync(f));
  for (const f of present) if (!fs.readFileSync(f, 'utf8').includes(MARKER)) fail(`${f} was not created by worker-bridge-setup; refusing to remove it`);
  const homeExists = fs.existsSync(o.home);
  // The checks below compare paths: the units name the real home and lsof reports the real path. A --home that reaches the
  // home through a symbolic link would pass them and then delete the real home, so purge only the real path.
  if (o.purge && homeExists) {
    const real = fs.realpathSync(o.home);
    if (real !== path.resolve(o.home)) fail(`${o.home} passes through a symbolic link (its real path is ${real}); nothing was removed. Run the same command with --home ${real}`);
  }
  if (o.purge && homeExists && !isBridgeHome(o.home, o.worker)) fail(`${o.home} is not a bridge home for worker ${o.worker}; refusing to purge it`);
  if (!present.length && !(o.purge && homeExists)) { log(`Nothing to remove for worker ${o.worker}.`); return; }
  if (o.purge && homeExists) {
    const { named: users, unreadable } = unitsNamingHome(unitDir, o.home, present);
    if (unreadable.length) fail(`${unreadable.join(', ')} could not be read, so it is not known whether a service that uses ${o.home} is defined there. Nothing was removed. Make ${unreadable.length > 1 ? 'them' : 'it'} readable (or delete ${unreadable.length > 1 ? 'them' : 'it'} once the service is stopped), then run this command again.`);
    if (users.length) {
      const stop = linux
        ? users.map(f => `systemctl --user disable --now ${path.basename(f)}`).join('; ')
        : users.map(f => `launchctl bootout ${launchDomains(process.getuid())[0]} ${f} (or ${launchDomains(process.getuid())[1]} for an agent that an earlier release loaded)`).join('; ');
      fail(`${o.home} is still named by ${users.join(', ')}; a service that uses this home may be running. Nothing was removed. Stop it (${stop}), delete that file, then run this command again.`);
    }
  }

  if (present.length && linux) systemctl(['disable', '--now', ...present.map(f => path.basename(f))], env, spawn, o);
  if (!linux) for (const plist of present) {
    const label = path.basename(plist, '.plist'), uid = process.getuid();
    const [userDomain, guiDomain] = launchDomains(uid);
    const r = launchctl(['bootout', userDomain, plist], env, spawn);
    const g = r.status === 0 ? r : launchctl(['bootout', guiDomain, plist], env, spawn); // loaded by an older release
    if (r.status === 0 || g.status === 0) log(`Stopped ${label}`);
    else if (launchDomains(uid).some(domain => launchctl(['print', `${domain}/${label}`], env, spawn).status === 0)) {
      fail(`launchctl bootout ${guiDomain} ${plist} failed (exit ${g.status ?? g.signal}) and the agent is still loaded: ${String(g.stderr).trim()}. Nothing was removed.`);
    } else log(`${label} was not loaded; nothing to stop`);
  }
  for (const f of present) { fs.rmSync(f); log(`Removed ${f}`); }
  if (present.length && linux) systemctl(['daemon-reload'], env, spawn, o);
  if (o.purge && homeExists) {
    // The service that was just stopped needs a moment to exit.
    const waitMs = Number(env.DALAN_PURGE_WAIT_MS ?? 5000);
    let probe = holderProbe(o.home);
    for (let waited = 0; (probe.holders.length || probe.unknown) && waited < waitMs; waited += 100) {
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
      probe = holderProbe(o.home);
    }
    const retry = `--remove --worker ${o.worker} --home ${o.home} --purge-home`;
    if (probe.holders.length) {
      fail(`The service is removed, but ${o.home} is kept: ${probe.holders.map(h => `process ${h.pid}${h.command ? ` (${h.command.slice(0, 80)})` : ''}`).join(', ')} still hold(s) its bridge database open. Stop ${probe.holders.length > 1 ? 'them' : 'it'}, then run the same command again: ${retry}`);
    }
    if (probe.unknown) {
      fail(`The service is removed, but ${o.home} is kept: it could not be checked whether a process still holds its bridge database open (${probe.unknown}). Make sure nothing uses ${o.home}, fix that check (for example install lsof), then run the same command again: ${retry}`);
    }
    fs.rmSync(o.home, { recursive: true, force: true }); log(`Removed bridge home ${o.home}`);
  }
  else if (o.purge) log(`No bridge home at ${o.home}`);
}

// Point an existing service at the code that runs this script. An npm install of a renamed package, or a moved checkout,
// leaves the unit naming the old directory. Only the old directory text changes; port, home and environment stay as they are.
function repointUnit(o, { platform, env, log }) {
  const unitDir = unitDirFor(platform, env);
  if (!unitDir) fail('--repoint is not supported on this platform (only Linux and macOS have units)');
  const linux = platform === 'linux';
  const names = linux ? [`dot-bridge-${o.worker}.service`] : [`${launchLabel(o.worker)}.plist`];
  const present = names.map(n => path.join(unitDir, n)).filter(f => fs.existsSync(f));
  if (!present.length) fail(`no service unit for worker ${o.worker} in ${unitDir}; nothing to repoint`);
  const changes = present.map(file => {
    const text = fs.readFileSync(file, 'utf8');
    if (!text.includes(MARKER)) fail(`${file} was not created by worker-bridge-setup; refusing to change it`);
    const match = linux ? /^WorkingDirectory=(\S+)$/m.exec(text) : /<key>WorkingDirectory<\/key>\s*<string>([^<]+)<\/string>/.exec(text);
    if (!match) fail(`${file} has no WorkingDirectory; refusing to guess the old code directory`);
    if (!linux && match[1] !== o.repo && !text.includes(`<string>${path.join(match[1], 'src/server.mjs')}</string>`)) fail(`${file} runs a script other than ${path.join(match[1], 'src/server.mjs')}; refusing to guess what to change`);
    return { file, text, old: match[1] };
  });
  for (const { file, text, old } of changes) {
    let next = text;
    // Change the code directory and the script argument only. HOME, the environment, the interpreter and the log paths can
    // name a path below the old code directory; they are not code paths and stay as they are.
    if (old !== o.repo) {
      next = linux
        ? next.replace(/^WorkingDirectory=.*$/m, () => `WorkingDirectory=${o.repo}`)
        : next.replace(/(<key>WorkingDirectory<\/key>\s*<string>)[^<]*(<\/string>)/, (_, head, tail) => `${head}${o.repo}${tail}`)
          .replace(`<string>${path.join(old, 'src/server.mjs')}</string>`, () => `<string>${path.join(o.repo, 'src/server.mjs')}</string>`);
    }
    // A plist from an older release lacks the session types that let launchd load it into the user domain.
    const addSessionTypes = !linux && !next.includes('<key>LimitLoadToSessionType</key>');
    if (addSessionTypes) {
      next = next.replace(/(  <key>KeepAlive<\/key>\s*<true\/>\n)/, `$1  <key>LimitLoadToSessionType</key>\n  <array>\n${SESSION_TYPES.map(type => `    <string>${type}</string>\n`).join('')}  </array>\n`);
    }
    if (next === text) { log(`${file} already points at ${o.repo}`); continue; }
    if (!fs.existsSync(path.join(o.repo, 'src/server.mjs'))) fail(`${o.repo}/src/server.mjs does not exist; run this from the installed package`);
    const tmp = `${file}.repoint-${process.pid}`;
    fs.writeFileSync(tmp, next, { mode: fs.statSync(file).mode & 0o777, flag: 'wx' });
    fs.renameSync(tmp, file);
    log(old === o.repo ? `Updated ${file}: added the launchd session types (${SESSION_TYPES.join(', ')})` : `Repointed ${file}: ${old} -> ${o.repo}${addSessionTypes ? '; added the launchd session types' : ''}`);
  }
  const [userDomain] = launchDomains(process.getuid?.());
  log(linux
    ? `Restart it: systemctl --user daemon-reload && systemctl --user restart dot-bridge-${o.worker}.service`
    : `Load it again: launchctl bootstrap ${userDomain} PLIST && launchctl kickstart -k ${userDomain}/LABEL (stop it first with launchctl bootout ${userDomain} PLIST, or bootout gui/${process.getuid()} PLIST for an agent that an older release loaded)`);
}

function verifyRetryTarget(o, { platform, env }) {
  const configDir=defaultPath(o.home,'.config/dot-bridge');
  const workersFile=defaultPath(o.home,'.config/dot-bridge/workers.json');
  const asFile=defaultPath(o.home,'.config/dot-bridge/as.json');
  const envFile=path.join(configDir,'env');
  const keysFile=path.join(configDir,'as-jwks.json');
  const cookieKeysFile=path.join(configDir,'as-cookie-keys.json');
  const urlFile=path.join(o.home,'resource-url');
  assertOwnedPath(o.home, o.home, 'directory', 'bridge home');
  assertOwnedPath(o.home, path.join(o.home,'.config'), 'directory', 'bridge config path');
  assertOwnedPath(o.home, configDir, 'directory', 'bridge config path');
  const workers=JSON.parse(readOwnedFile(o.home,workersFile,'worker profile'));
  const as=JSON.parse(readOwnedFile(o.home,asFile,'issuer config'));
  const envText=readOwnedFile(o.home,envFile,'bridge environment');
  const resource=readOwnedFile(o.home,urlFile,'resource URL').trim();
  readOwnedFile(o.home,keysFile,'signing key');
  readOwnedFile(o.home,cookieKeysFile,'cookie keys');
  const secretMatch=/^BRIDGE_PATH_SECRET=([a-f0-9]{64})\n?$/.exec(envText);
  if(!secretMatch) fail('--retry-public-check refused: the saved bridge path secret is missing or invalid');
  loadKeys(configDir);
  if(!Object.hasOwn(workers.workers??{},o.worker)) fail(`--retry-public-check refused: ${o.home} has no worker profile named ${o.worker}`);
  let saved;
  try { saved=new URL(resource); } catch { fail('--retry-public-check refused: the saved resource URL is invalid'); }
  if(saved.origin!==o.publicUrl||saved.pathname!==`/${saved.pathname.split('/')[1]}/mcp`||!/^\/[a-f0-9]{64}\/mcp$/.test(saved.pathname)) fail('--retry-public-check refused: --public-url does not match this home resource URL');
  if(saved.pathname!==`/${secretMatch[1]}/mcp`) fail('--retry-public-check refused: the saved resource URL does not match this home path secret');
  if(as.public_url!==o.publicUrl) fail('--retry-public-check refused: --public-url does not match this home issuer');
  const exposureFile=expose.recordPath(o.home,o.worker);
  const exposure=JSON.parse(readOwnedFile(o.home,exposureFile,'exposure record'));
  const publicPort=Number(new URL(o.publicUrl).port||443);
  if(exposure.worker!==o.worker||exposure.public_url!==o.publicUrl||exposure.local_port!==o.port) fail('--retry-public-check refused: --public-url or --port does not match this worker exposure record');
  if (exposure.mode === 'tailscale') {
    if(exposure.dns_name!==saved.hostname||exposure.public_port!==publicPort) fail('--retry-public-check refused: --public-url or --port does not match this worker exposure record');
  } else if (exposure.mode === 'ngrok') {
    const configFile=expose.ngrokConfigPath(o.home,o.worker);
    const config=readOwnedFile(o.home,configFile,'ngrok config');
    if(exposure.domain!==saved.hostname||exposure.ngrok_config!==configFile||config!==expose.ngrokConfigText({worker:o.worker,domain:exposure.domain,localPort:o.port})) fail('--retry-public-check refused: ngrok domain or config does not match this worker exposure record');
  } else fail('--retry-public-check refused: exposure record has an unsupported mode');
  const dir=unitDirFor(platform,env), unit=platform==='darwin'?path.join(dir,`${launchLabel(o.worker)}.plist`):path.join(dir,`dot-bridge-${o.worker}.service`);
  const configRoot=platform==='darwin'?(env.HOME||os.homedir()):(env.XDG_CONFIG_HOME&&path.isAbsolute(env.XDG_CONFIG_HOME)?env.XDG_CONFIG_HOME:path.join(os.homedir(),'.config'));
  assertOwnedPath(configRoot,dir,'directory','service unit directory');
  const text=readOwnedFile(configRoot,unit,'service unit');
  const expected=platform==='darwin'?plistText(o):unitFiles(o).files[`dot-bridge-${o.worker}.service`];
  // Accept only the previous generator's equivalent setting names; retain every
  // other byte check so a customized service cannot become a retry target.
  const compatibleText=text.replace(/^Environment=DOT_BRIDGE_(AUTH_MODE|ENABLE_WORKSPACE|PORT)=/gm,'Environment=DALAN_$1=').replace(/<key>DOT_BRIDGE_(AUTH_MODE|ENABLE_WORKSPACE|PORT)<\/key>/g,'<key>DALAN_$1</key>');
  if(compatibleText!==expected) fail(`--retry-public-check refused: ${unit} does not exactly match the generated worker, HOME, executable, working directory and port`);
  if(platform==='linux') assertNoSystemdOverrides(unit,env);
  return { url:o.publicUrl, dnsName:saved.hostname };
}

// `--start` returns as soon as the service manager accepts the unit, but the bridge needs a moment more before its admin
// socket answers. Commands run in that gap fail with `connect ENOENT .../admin.sock`, so --start waits for a real connection.
const connectsOnce = socketPath => spawnSync(process.execPath, ['-e',
  "const s=require('node:net').connect(process.argv[1]);s.on('connect',()=>process.exit(0));s.on('error',()=>process.exit(1));setTimeout(()=>process.exit(1),2000)", socketPath], { stdio: 'ignore' }).status === 0;
export function waitForAdminSocket({ socketPath, timeoutMs = 30000, intervalMs = 250, probe = connectsOnce, now = Date.now, sleep = ms => Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms) }) {
  const deadline = now() + timeoutMs;
  for (;;) {
    if (probe(socketPath)) return true;
    if (now() >= deadline) return false;
    sleep(intervalMs);
  }
}
function waitForStartedBridge(o, env, platform, waitForSocket) {
  // Only an explicit "0" skips the wait (tests that replace the service manager have no bridge to wait for);
  // an empty or invalid value keeps the 30 s default.
  const raw = readEnv('DALAN_SETUP_SOCKET_WAIT_MS', env);
  if (String(raw ?? '').trim() === '0') return;
  const requested = Number(raw);
  const budget = raw != null && String(raw).trim() !== '' && Number.isFinite(requested) && requested > 0 ? requested : 30000;
  if (waitForSocket({ socketPath: o.socketPath, timeoutMs: budget })) return;
  const where = platform === 'darwin' ? `the log files under ${path.join(o.home, 'logs')}` : `journalctl --user -u dot-bridge-${o.worker}.service`;
  fail(`the service was started but the bridge did not answer on its admin socket ${o.socketPath} within ${Math.round(budget / 1000)} s. Read the service log with ${where}. Generated state is left in place; remove this install with: ${recoveryCommand(o)}`);
}

function runUnlocked(argv, { platform = process.platform, env = process.env, log = console.log, verifyPublic = expose.verifyPublic, resolve4 = expose.makePublicResolver(), preflight = expose.preflight, applyFunnel = expose.applyFunnel, initHome, spawn = spawnSync, tailscale, waitForSocket = waitForAdminSocket, holderProbe } = {}, parsed = null) {
  const o = parsed ?? parseOptions(argv, platform);
  if (o.help) {
    log('usage: node scripts/worker-bridge-setup.mjs --worker NAME --public-url https://HOST --port N [--home DIR] [--lan-forward ADDR:PORT] [--write-units-only] [--start] [--no-repo-tools]');
    log('   or: node scripts/worker-bridge-setup.mjs --worker NAME --port N --expose tailscale [--funnel-port 443|8443|10000] [--start]');
    log('   or: node scripts/worker-bridge-setup.mjs --worker NAME --port N --expose ngrok --ngrok-domain ASSIGNED-DOMAIN [--start]');
    log('       node scripts/worker-bridge-setup.mjs --retry-public-check --worker NAME --public-url https://HOST --port N [--home DIR]');
    log('       node scripts/worker-bridge-setup.mjs --repoint --worker NAME   (point an existing service at this copy of the code)');
    log('       node scripts/worker-bridge-setup.mjs --remove --worker NAME [--home DIR] [--purge-home]   (also turns off a recorded Funnel rule)');
    return;
  }
  if (o.repoint) return repointUnit(o, { platform, env, log });
  if (o.remove) {
    // The exposure record lives in the bridge home; turn our Funnel rule off before the unit and (optionally) the home go.
    const record = expose.recordPath(o.home, o.worker);
    if (fs.existsSync(record)) expose.removeExposure({ file: record, log, ...(tailscale ? { tailscale } : {}) });
    return removeUnit(o, { platform, env, log, spawn, ...(holderProbe ? { holderProbe } : {}) });
  }
  const linux = platform === 'linux', darwin = platform === 'darwin';
  if (o.start && !linux && !darwin) fail('--start is not supported on this platform: only Linux (systemd) and macOS (launchd) have a service unit');
  const unitDir = unitDirFor(platform, env);
  const { files, enable } = linux ? unitFiles(o) : { files: darwin ? { [`${launchLabel(o.worker)}.plist`]: plistText(o) } : {}, enable: [] };

  if(o.retryPublicCheck) {
    const {url,dnsName}=verifyRetryTarget(o,{platform,env});
    if(readEnv('DALAN_EXPOSE_SKIP_PUBLIC_CHECK',env)==='1') { log('SKIPPED public check (DALAN_EXPOSE_SKIP_PUBLIC_CHECK=1; tests only)'); return; }
    const exposureFile=expose.recordPath(o.home,o.worker);
    const retryRecord=JSON.parse(readOwnedFile(o.home,exposureFile,'exposure record'));
    if(retryRecord.mode==='ngrok') expose.updateExposureState(exposureFile,'unverified');
    return verifyPublic({url,dnsName,resolve4,log}).then(ok=>{
      if(!ok) fail(`public verification failed; the service, home and keys were left in place. Retry after the public route is ready with: ${publicRetryCommand(o,url)}. To remove this install: ${recoveryCommand(o)}`);
      const record=JSON.parse(readOwnedFile(o.home,exposureFile,'exposure record'));
      if(record.mode==='ngrok') expose.updateExposureState(exposureFile,'verified');
    });
  }

  // Check everything before the first write so a refusal leaves nothing behind.
  if (!o.writeUnitsOnly) assertNoSymlinkInCreationPath(path.dirname(o.home), '--home parent');
  if (unitDir) assertNoSymlinkInCreationPath(unitDir, 'service unit directory', true);
  if (!o.writeUnitsOnly) {
    try { fs.lstatSync(o.home); fail(`${o.home} already exists; refusing to reuse or change it. Pick a new --home or remove it yourself`); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  if (unitDir) for (const f of Object.keys(files)) if (fs.existsSync(path.join(unitDir, f))) fail(`${path.join(unitDir, f)} already exists; refusing to overwrite it`);
  if (darwin && !lintPlist(files[`${launchLabel(o.worker)}.plist`], env)) log('plutil not found: skipped the plist lint');
  // --expose tailscale: read-only preflight and port choice. Nothing above or below writes until this passes.
  let exposure = null;
  if (o.expose?.mode === 'tailscale') {
    const pf = preflight({ platform });
    for (const w of pf.warnings) log(`WARN ${w}`);
    const port = expose.choosePort({ requested: o.expose.funnelPort, allowed: pf.allowed, occupied: pf.occupied });
    o.publicUrl = expose.publicUrl(pf.dnsName, port);
    exposure = { mode: 'tailscale', dnsName: pf.dnsName, port, url: o.publicUrl, file: expose.recordPath(o.home, o.worker) };
  } else if (o.expose?.mode === 'ngrok') {
    // Nothing is run here. The URL is derived from the assigned domain; the config and commands come after the units.
    o.publicUrl = `https://${o.expose.domain}`;
    exposure = { mode: 'ngrok', domain: o.expose.domain, url: o.publicUrl, file: expose.recordPath(o.home, o.worker) };
  }

  if (o.start) checkStartReadiness(platform, env);
  if (o.start) warnIfLingeringDisabled(platform, env, log, spawn);

  let urlFile = path.join(o.home, 'resource-url');
  if (!o.writeUnitsOnly) { urlFile = writeHome(o, platform, initHome); log(`Home ready: ${o.home} (mode 0700), worker ${o.worker}, issuer ${o.publicUrl}`); }

  const uid = process.getuid?.();
  if (!unitDir) {
    log('service unit: not supported on this platform. Home and init are done; start `node src/server.mjs` yourself with');
    log(`  HOME=${o.home} NODE_ENV=production DALAN_AUTH_MODE=builtin${o.repoTools ? ' DALAN_ENABLE_WORKSPACE=1' : ''} DALAN_PORT=${o.port}`);
  } else if (linux) {
    fs.mkdirSync(unitDir, { recursive: true });
    for (const [f, text] of Object.entries(files)) { writeExclusive(path.join(unitDir, f), text, 0o644, 'service unit', o); log(`Wrote ${path.join(unitDir, f)}`); }
    const command = `systemctl --user daemon-reload && systemctl --user enable --now ${enable.join(' ')}`;
    if (o.start) { systemctl(['daemon-reload'], env, spawn, o); systemctl(['enable', '--now', ...enable], env, spawn, o); waitForStartedBridge(o, env, platform, waitForSocket); log(`Started: ${enable.join(' ')}`); }
    else log(`Not started. To start:\n  ${command}`);
  } else {
    fs.mkdirSync(unitDir, { recursive: true });
    const plist = path.join(unitDir, `${launchLabel(o.worker)}.plist`);
    writeExclusive(plist, files[`${launchLabel(o.worker)}.plist`], 0o644, 'launch agent', o);
    log(`Wrote ${plist}`);
    const domain = launchDomains(uid)[0];
    const stop = `launchctl bootout ${domain} ${plist}`;
    if (o.start) {
      const r = launchctl(['bootstrap', domain, plist], env, spawn);
      if (r.status !== 0) fail(`launchctl bootstrap ${domain} ${plist} failed (exit ${r.status ?? r.signal}): ${String(r.stderr).trim()}. The plist and home are left in place; remove this install with: ${recoveryCommand(o)}`);
      // On macOS 26 a bootstrapped agent can stay loaded but never spawn. Ask launchd to start it, then check that it runs.
      const kick = launchctl(['kickstart', `${domain}/${launchLabel(o.worker)}`], env, spawn);
      if (kick.status !== 0) log(`Warning: launchctl kickstart failed (exit ${kick.status ?? kick.signal}): ${String(kick.stderr).trim()}. The agent is loaded; if the bridge does not answer, check ${path.join(o.home, 'logs')}.`);
      waitForStartedBridge(o, env, platform, waitForSocket);
      log(`Started: ${launchLabel(o.worker)}`);
      log(`To stop: ${stop}`);
    } else log(`Not started. To start:\n  launchctl bootstrap ${domain} ${plist}\nTo stop:\n  ${stop}`);
  }
  // Tailscale Funnel: our own rule on our own port, then proof that it maps exactly that port to the bridge.
  if (exposure?.mode === 'tailscale') {
    try { expose.writeExposureRecord({ file: exposure.file, worker: o.worker, dnsName: exposure.dnsName, port: exposure.port, localPort: o.port, url: exposure.url }); }
    catch (error) { throw new Error(`${error.message}. Generated state is left in place; remove this install with: ${recoveryCommand(o)}`); }
    try {
      applyFunnel({ dnsName: exposure.dnsName, port: exposure.port, localPort: o.port });
      expose.updateExposureState(exposure.file, 'active');
    } catch (error) {
      throw new Error(`${error.message}. Funnel intent is recorded; remove this exact owned rule and install with: ${recoveryCommand(o)}`);
    }
    log(`Funnel: ${exposure.url} -> http://127.0.0.1:${o.port} (tailscale funnel --https=${exposure.port}); record ${exposure.file}`);
  } else if (exposure?.mode === 'ngrok') {
    let configFile;
    try { configFile = expose.writeNgrokExposure({ home: o.home, worker: o.worker, domain: exposure.domain, localPort: o.port, file: exposure.file }); }
    catch (error) { throw new Error(`${error.message}. Generated state is left in place; remove this install with: ${recoveryCommand(o)}`); }
    log(`ngrok config: ${configFile} (mode 0600, no authtoken in it); record ${exposure.file}`);
    log(`Public URL: ${exposure.url} -> http://127.0.0.1:${o.port}. ngrok was NOT run. Run these yourself:`);
    for (const c of expose.ngrokCommands(configFile)) log(`  ${c}`);
    log(`QUOTA WARNING: ${expose.NGROK_QUOTA_WARNING}`);
  }
  if (o.lan) log(`LAN forwarder: ${o.lan.address}:${o.lan.port} -> 127.0.0.1:${o.port}. Point the reverse proxy there; anything on that network can reach it.`);
  log(`Resource URL file (private, mode 0600): ${urlFile}`);
  const dw = `dalan() { HOME=${shellQuote(o.home)} ${shellQuote(o.node)} ${shellQuote(path.join(o.repo, 'bin/dalan.mjs'))} "$@"; }`;
  log('Owner commands (run after the service is up):');
  log(`  ${dw}`);
  log(`  dalan connect start --worker ${o.worker}`);
  log('  dalan connect pending');
  log(`  dalan connect approve CODE --worker ${o.worker}`);
  log('  dalan connect signal-token    # save wake URL privately for hook-driven workers; print path; --rotate replaces it');
  if (!exposure) return undefined;
  if (exposure.mode === 'ngrok') {
    log(`Public status: unverified until the ngrok service is started and --retry-public-check succeeds. ngrok was not started. After starting it, verify with: ${publicRetryCommand(o, exposure.url)}`);
    return undefined;
  }
  // Public check only after the bridge starts. Returns a promise; the entry point awaits it and exits 1 on failure.
  const { dnsName, url } = exposure;
  if (!o.start) {
    log(`Public check runs with --start. By hand: dig @8.8.8.8 ${dnsName} A (or @1.1.1.1, @9.9.9.9) ; curl -sS -o /dev/null -w '%{http_code}' ${url}/admin  (expect 404)`);
    return undefined;
  }
  if (readEnv('DALAN_EXPOSE_SKIP_PUBLIC_CHECK',env) === '1') { log('SKIPPED public check (DALAN_EXPOSE_SKIP_PUBLIC_CHECK=1; tests only)'); return undefined; }
  return verifyPublic({ url, dnsName, resolve4, log }).then(ok => {
    if (!ok) fail(`public verification failed; the service, home and keys were left in place. Retry the check with: ${publicRetryCommand(o,url)}. To remove this install: ${recoveryCommand(o)}`);
  });
}

export function run(argv, seams = {}) {
  if (argv.includes('--help')) return runUnlocked(argv, seams);
  // Reject malformed arguments before creating the per-home lock directory.
  const parsed = parseOptions(argv, seams.platform ?? process.platform);
  // The lock is per user and host-wide by default, so installers with different HOME values still serialize on one unit directory.
  // DALAN_SETUP_LOCK_DIR (an absolute path) moves it, for example so concurrent test runs do not collide.
  const envRoot = (seams.env ?? process.env).DALAN_SETUP_LOCK_DIR;
  if (envRoot && !path.isAbsolute(envRoot)) fail('DALAN_SETUP_LOCK_DIR must be an absolute path');
  const release = acquireSetupLock(seams.setupLockRoot ?? (envRoot || undefined));
  try {
    const result = runUnlocked(argv, seams, parsed);
    if (result && typeof result.then === 'function') return result.finally(release);
    release();
    return result;
  } catch (error) {
    release();
    throw error;
  }
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { await run(process.argv.slice(2)); }
  catch (e) { console.error(`worker-bridge-setup: ${e.message}`); process.exit(1); }
}
