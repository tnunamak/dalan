const REPO = fileURLToPath(new URL('..', import.meta.url));
const SAFE_PATH = /^[A-Za-z0-9_@+=:,./-]+$/; // no space, quote, %, $ or newline: the value goes into a unit or plist as is
const PROXYD = ['/usr/lib/systemd/systemd-socket-proxyd', '/lib/systemd/systemd-socket-proxyd'];
const MARKER = 'Generated by scripts/worker-bridge-setup.mjs'; // --remove only deletes files that carry this text
class SetupRefusal extends Error {
  constructor(message) { super(message); this.name = 'SetupRefusal'; this.code = 'SETUP_REFUSED'; }
}
const fail = message => { throw new SetupRefusal(message); };
const launchLabel = worker => `org.dalan.dot-bridge-${worker}`;
// New services load into the user's launchd domain, not the GUI domain. A GUI domain whose session is idle or locked can be in
// "on-demand-only" mode: launchd then neither runs an agent at load nor restarts it after it is killed (KeepAlive has no effect).
// The user domain has no such mode. Agents that an older release loaded into the GUI domain are still found when they are removed.
const SESSION_TYPES = ['Aqua', 'Background']; // the user domain accepts an agent only if its plist allows the Background session
const launchDomains = uid => [`user/${uid}`, `gui/${uid}`];

// A version-pinned interpreter path (Homebrew Cellar, mise installs/node/<version>) breaks the unit on upgrade. Prefer a stable
// launcher path that resolves to the same binary.
function stableNode(execPath) {
  const real = fs.realpathSync(execPath);
  const userHome = os.userInfo().homedir || os.homedir();
  for (const candidate of ['/opt/homebrew/bin/node', '/usr/local/bin/node', path.join(userHome, '.local/share/mise/installs/node/lts/bin/node')]) {
    try { if (fs.realpathSync(candidate) === real) return candidate; } catch { /* not present */ }
  }
  return execPath;
}

function parseOptions(argv, platform) {
  const args = parseArgs(argv, {
    values: ['--worker', '--public-url', '--port', '--home', '--lan-forward', '--expose', '--funnel-port', '--ngrok-domain'],
    flags: ['--persistent', '--write-units-only', '--no-repo-tools', '--start', '--help', '--remove', '--purge-home', '--retry-public-check', '--repoint'],
  });
  if (args._.length) fail(`unexpected argument ${args._[0]}`);
  if (args['--help']) return { help: true };
  const worker = args['--worker'];
  if (!worker || !/^[a-z][a-z0-9_-]{0,31}$/.test(worker)) fail('--worker NAME is required (lowercase letters, digits, - and _; up to 32 characters)');
  const home = path.resolve(args['--home'] ?? path.join(os.homedir(), '.local/share/dbm'));
  if (args['--retry-public-check'] && args['--remove']) fail('--retry-public-check cannot be combined with --remove');
  if (args['--repoint']) {
    const others = ['--remove', '--retry-public-check', '--start', '--write-units-only', '--public-url', '--port', '--home', '--lan-forward', '--expose', '--funnel-port', '--ngrok-domain', '--purge-home', '--no-repo-tools', '--persistent'].filter(flag => args[flag] !== undefined && args[flag] !== false);
    if (others.length) fail(`--repoint takes only --worker; remove ${others.join(' ')}`);
    const repo = REPO.replace(/\/$/, '');
    if (!SAFE_PATH.test(repo)) fail(`repo path contains a character that is not safe in a unit file: ${JSON.stringify(repo)}`);
    return { repoint: true, worker, repo };
  }
  if (args['--remove']) {
    // Users rerun their install command with --remove appended, so install-only flags are ignored, not refused.
    const ignored = ['--public-url', '--port', '--lan-forward', '--write-units-only', '--start', '--no-repo-tools', '--expose', '--funnel-port', '--ngrok-domain'].filter(flag => args[flag] !== undefined && args[flag] !== false);
    if (ignored.length) console.error(`worker-bridge-setup: ignoring install-only flags with --remove: ${ignored.join(' ')}`);
    return { remove: true, worker, home, purge: !!args['--purge-home'] };
  }
  if (args['--purge-home']) fail('--purge-home is only valid with --remove');
  const mode = args['--expose'];
  if (args['--retry-public-check'] && (mode || args['--start'] || args['--write-units-only'] || args['--remove'])) fail('--retry-public-check takes --public-url and checks an existing service; omit --expose, --start, --write-units-only and --remove');
  if (mode !== undefined && mode !== 'tailscale' && mode !== 'ngrok') fail('--expose only supports "tailscale" (default on Linux and macOS) or "ngrok" (fallback)');
  if (args['--funnel-port'] !== undefined && mode !== 'tailscale') fail('--funnel-port needs --expose tailscale');
  if (args['--ngrok-domain'] !== undefined && mode !== 'ngrok') fail('--ngrok-domain needs --expose ngrok');
  if (mode === 'ngrok' && args['--ngrok-domain'] === undefined) fail('--expose ngrok needs --ngrok-domain <assigned-domain> (the static domain from your ngrok dashboard)');
  const ngrokDomain = args['--ngrok-domain'];
  if (ngrokDomain !== undefined && !/^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$/.test(ngrokDomain)) fail('--ngrok-domain must be a bare host name such as your-name.ngrok-free.app (no https:// and no path)');
  if (mode && args['--public-url'] !== undefined) fail(`--public-url is derived with --expose ${mode}; do not pass both`);
  const funnelPort = args['--funnel-port'] === undefined ? undefined : Number(args['--funnel-port']);
  if (funnelPort !== undefined && (!Number.isInteger(funnelPort) || funnelPort < 1 || funnelPort > 65535)) fail('--funnel-port must be a port number');
  const publicUrl = mode ? null : parsePublicUrl(args['--public-url']);
  const port = Number(args['--port']);
  if (!Number.isInteger(port) || port < 1024 || port > 65535) fail('--port N is required (1024-65535)');
  const node = stableNode(process.execPath);
  const repo = REPO.replace(/\/$/, '');
  // Unix socket paths are limited (104 bytes on macOS, 108 on Linux); the owner socket lives under the bridge home.
  const socketPath = defaultPath(home,'.local/share/dot-bridge/admin.sock');
  if (Buffer.byteLength(socketPath) >= 104) fail(`--home is too long: the owner socket path would be ${Buffer.byteLength(socketPath)} bytes (limit 103); choose a shorter home`);
  for (const [label, value] of [['--home', home], ['node path', node], ['repo path', repo]]) {
    if (!SAFE_PATH.test(value)) fail(`${label} contains a character that is not safe in a unit file: ${JSON.stringify(value)}`);
  }
  let lan = null;
  if (args['--lan-forward']) {
    if (platform === 'darwin') fail('--lan-forward is Linux only (it needs a systemd socket); it is not supported on macOS');
    const m = /^(\d{1,3}(?:\.\d{1,3}){3}):(\d{1,5})$/.exec(args['--lan-forward']);
    const lanPort = m && Number(m[2]);
    if (!m || m[1].split('.').some(n => Number(n) > 255) || lanPort < 1 || lanPort > 65535) fail('--lan-forward must look like 198.51.100.10:8789');
    if (lanPort === port && ['127.0.0.1', '0.0.0.0'].includes(m[1])) fail('--lan-forward would collide with the bridge port');
    lan = { address: m[1], port: lanPort };
  }
  if (args['--write-units-only'] && args['--start']) fail('--start and --write-units-only exclude each other');
  return {
    worker, publicUrl, port, home, socketPath, node, repo, lan, writeUnitsOnly: !!args['--write-units-only'], start: !!args['--start'],
    repoTools: !args['--no-repo-tools'], retryPublicCheck: !!args['--retry-public-check'],
    expose: mode === 'tailscale' ? { mode, funnelPort } : mode === 'ngrok' ? { mode, domain: ngrokDomain } : null,
  };
}

function parsePublicUrl(value) {
  if (!value) fail('--public-url https://HOST is required');
  let url;
  try { url = new URL(value); } catch { fail('--public-url must be an origin URL'); }
  if (url.protocol !== 'https:') fail('--public-url must use https');
  const withoutDefaultPort = value.replace(/:443(?=\/|$)/, '');
  if (url.username || url.password || url.search || url.hash || url.pathname !== '/' || (withoutDefaultPort !== url.origin && withoutDefaultPort !== `${url.origin}/`)) {
    fail('--public-url must contain only scheme, host and optional port');
  }
  return url.origin;
}

