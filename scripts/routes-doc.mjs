// Writes docs/routes.md from the Gozar registry that is installed, so the list of routes is Gozar's data and never Dalan's.
// It asks Gozar's catalog (through the public route API) with every probe faked, so no provider runs and nothing leaves this computer.
//   node scripts/routes-doc.mjs           write docs/routes.md
//   node scripts/routes-doc.mjs --check   exit 1 when docs/routes.md differs from what this script would write now
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { routesQuery } from '../src/routes.mjs';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ROUTES_DOC = path.join(repo, 'docs', 'routes.md');

const list = values => values.length ? values.join(', ') : 'none';
const oneLine = text => String(text).replace(/\s+/g, ' ').trim();

export function renderRoutesDoc(catalog) {
  const candidates = [...catalog.candidates].sort((a, b) => a.providerId < b.providerId ? -1 : a.providerId > b.providerId ? 1 : 0);
  const out = [
    '# Routes Gozar offers for Dalan', '',
    '<!-- Generated by scripts/routes-doc.mjs from the installed Gozar registry. Do not edit; run `node scripts/routes-doc.mjs` to refresh. -->', '',
    'Dalan needs one Gozar route to publish its address. This page lists the routes in the Gozar release Dalan bundles, as Gozar describes them. Pick one with `--route <id>`:', '',
    '```bash', 'dalan routes                              # what Gozar offers on this computer, and whether each route is usable now',
    'dalan service install --worker NAME --route <id>', 'dalan try --public --route <id>', '```', '',
    'Whether a route is usable depends on your computer and accounts, so `dalan routes` is the check that counts. This page does not say which route to choose.', '',
  ];
  for (const c of candidates) {
    const p = c.properties;
    out.push(`## ${c.display.label}`, '', `- Id: \`${c.providerId}\` (use \`--route ${c.providerId}\`)`, `- ${oneLine(c.display.description)}`, `- Needs: ${oneLine(c.display.needs)}`,
      `- Reach: ${p.reach}; transport: ${p.transport}; lifetimes: ${list(p.lifetimes)}`,
      `- Address: ${p.address.stability} (${p.address.scope}${p.address.conditions.length ? `; ${p.address.conditions.join('; ')}` : ''}); public ports: ${p.address.ports === null ? 'assigned by the provider' : list(p.address.ports)}`,
      `- Proof before publishing: checked from ${p.proof.vantage}; checks: ${list(p.proof.checks)}`,
      `- Traffic: readers ${list(p.traffic.readers)}; provider can read payload: ${p.traffic.providerCanReadPayload === null ? 'unknown' : p.traffic.providerCanReadPayload ? 'yes' : 'no'}; TLS ends at: ${p.traffic.tlsTermination}`,
      `- Cost: ${oneLine(p.cost.summary)}; account needed: ${p.needsAccount === null ? 'unknown' : p.needsAccount ? 'yes' : 'no'}`,
      `- Consent text: ${oneLine(c.disclosure.text)}`);
    for (const link of c.disclosure.links) out.push(`  - ${link.label}: ${link.href}`);
    out.push('');
  }
  return `${out.join('\n').trimEnd()}\n`;
}

async function defaultApi(home) {
  const { createRouteApi, fakeReadContext } = await import('@tnunamak/gozar/testing');
  return createRouteApi({ readContext: fakeReadContext({ home }) });
}

export async function generate({ api } = {}) {
  const home = fs.mkdtempSync(path.join(os.tmpdir(), 'routes-doc-'));
  try {
    const gozar = api ?? await defaultApi(home);
    return renderRoutesDoc(await gozar.catalogRoutes(routesQuery({ env: { GOZAR_HOME: home } })));
  } finally { fs.rmSync(home, { recursive: true, force: true }); }
}

export async function main({ argv = process.argv.slice(2), api, file = ROUTES_DOC, out = line => process.stdout.write(`${line}\n`) } = {}) {
  const unknown = argv.filter(arg => arg !== '--check');
  if (unknown.length) { out(`unknown option ${unknown[0]}; usage: node scripts/routes-doc.mjs [--check]`); return 2; }
  const wanted = await generate({ api });
  if (argv.includes('--check')) {
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (current === wanted) return 0;
    out(`${path.relative(repo, file)} is ${current === null ? 'missing' : 'stale'}: run node scripts/routes-doc.mjs and commit the result`);
    return 1;
  }
  fs.writeFileSync(file, wanted);
  out(`wrote ${path.relative(repo, file)}`);
  return 0;
}

if (import.meta.url === `file://${process.argv[1]}`) main().then(code => { process.exitCode = code; }, error => { process.stderr.write(`routes-doc: ${error.message}\n`); process.exitCode = 1; });
